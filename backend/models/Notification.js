const mongoose = require('mongoose');

const notificationSchema = new mongoose.Schema({
  user: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'User',
    required: true,
    index: true
  },
  title: {
    type: String,
    required: true,
    trim: true
  },
  message: {
    type: String,
    required: true
  },
  read: {
    type: Boolean,
    default: false
  },
  type: {
    type: String,
    enum: ['reminder', 'milestone', 'system', 'recommendation'],
    default: 'system'
  }
}, {
  timestamps: true
});

module.exports = mongoose.model('Notification', notificationSchema);
